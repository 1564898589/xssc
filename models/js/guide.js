/**
 * guide.js —— 每个场景的「为什么这样选」内容层。
 *
 * 目的：让销售在场景里直接看到四件事，而不是只看到一堆产品名 ——
 *   ① 这格设备是干什么的（use）
 *   ② 行业里常见怎么做的（common）—— **包含不用我们的做法，且写明客户为什么那样选**
 *   ③ 什么条件下我们的产品才真正进得去（fit）
 *   ④ 什么情况下客户**不会**选我们，以及那是客户的合理选择（notFit）
 *   ⑤ 拜访先问哪几句，用来判断这个客户值不值得投入（ask）
 *
 * ⚠️ 证据分级（`ev`）——这是本文件最重要的纪律：
 *   'std'   = 有公开依据可查（国家标准 / 反措要求 / 招投标法规 / 产品手册 / 行业典型设计）
 *   'judge' = 工程分析，是我方基于公开信息的判断，**不是事实陈述**
 *   界面上两种标签必须能分辨。**没有证据的数字一律不写** ——
 *   不写「能省 X 元」「减少 N 次故障」「替代 M 只」这类无法核实的量。
 *
 * ⚠️ 口径红线：
 *   · 不贬低任何友商，不说「客户不懂」；notFit 一律写成**客户视角的合理理由**；
 *   · 不把「某类客户」整体判死（例如成套厂），而是按**出图权 / 采购权 / 项目性质**分情况说；
 *   · 不编型号、不编参数、不声称与实物一致。
 */

